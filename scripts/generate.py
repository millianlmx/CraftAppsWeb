#!/usr/bin/env python3
"""Generate docker-compose.yml and hub/nginx.conf from apps.json.

    scripts/generate.py           # write the files
    scripts/generate.py --check   # exit 1 if they are out of date (CI)

Both outputs are committed so Portainer can deploy the compose file straight from the repo.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# GENERATED by scripts/generate.py from apps.json. Do not edit.\n"


def load_apps():
    apps = json.loads((ROOT / "apps.json").read_text())["apps"]
    ids = [a["id"] for a in apps]
    assert len(ids) == len(set(ids)), "duplicate app id"
    for a in apps:
        assert set(a) >= {"id", "name", "tagline", "color", "web_dir"}, a
        assert a["id"] == a["id"].lower() and "/" not in a["id"], a["id"]
    return apps


def compose(apps):
    out = [HEADER, """#
# Portainer stack. Only the hub joins the external `traefik-network`; the apps sit on an
# internal network and the hub reverse-proxies them under /<app>/.
#
# Stack variables (Portainer "Environment variables" or a .env file):
#   IMAGE_PREFIX       registry/namespace of the images       (default ghcr.io/millianlmx)
#   TAG                image tag for every app and the hub    (default latest)
#   HUB_HOST           public hostname routed by Traefik      (required)
#   TRAEFIK_ENTRYPOINT Traefik entrypoint name                (default websecure)
#   TRAEFIK_RESOLVER   Traefik certificate resolver           (default letsencrypt)
#   TRAEFIK_NETWORK    the external Traefik network           (default traefik-network)

x-app: &app
  restart: unless-stopped
  read_only: true
  tmpfs:
    - /tmp
  networks:
    - apps
  healthcheck:
    test: ["CMD", "wget", "-q", "-O", "/dev/null", "http://127.0.0.1:8080/healthz"]
    interval: 30s
    timeout: 3s
    retries: 3
    start_period: 5s
  logging:
    driver: json-file
    options:
      max-size: "5m"
      max-file: "2"

services:
  hub:
    image: ${IMAGE_PREFIX:-ghcr.io/millianlmx}/craft-apps-hub:${TAG:-latest}
    restart: unless-stopped
    read_only: true
    tmpfs:
      - /tmp
    networks:
      - apps
      - traefik
    labels:
      traefik.enable: "true"
      traefik.docker.network: ${TRAEFIK_NETWORK:-traefik-network}
      traefik.http.routers.craft-hub.rule: Host(`${HUB_HOST:?set HUB_HOST}`)
      traefik.http.routers.craft-hub.entrypoints: ${TRAEFIK_ENTRYPOINT:-websecure}
      traefik.http.routers.craft-hub.tls: "true"
      traefik.http.routers.craft-hub.tls.certresolver: ${TRAEFIK_RESOLVER:-letsencrypt}
      traefik.http.services.craft-hub.loadbalancer.server.port: "8080"
    healthcheck:
      test: ["CMD", "wget", "-q", "-O", "/dev/null", "http://127.0.0.1:8080/healthz"]
      interval: 30s
      timeout: 3s
      retries: 3
      start_period: 5s
    logging:
      driver: json-file
      options:
        max-size: "5m"
        max-file: "2"
"""]
    for a in apps:
        out.append(f"""
  {a["id"]}:
    <<: *app
    image: ${{IMAGE_PREFIX:-ghcr.io/millianlmx}}/{a["id"]}-web:${{TAG:-latest}}
""")
    out.append("""
networks:
  apps:
    internal: true
  traefik:
    external: true
    name: ${TRAEFIK_NETWORK:-traefik-network}
""")
    return "".join(out)


def hub_nginx(apps, hub):
    locations = []
    for a in apps:
        i = a["id"]
        if i == hub:
            continue
        locations.append(f"""
        location = /{i} {{ return 301 /{i}/; }}
        location /{i}/ {{
            set $upstream http://{i}:8080;
            rewrite ^/{i}/(.*)$ /$1 break;
            proxy_pass $upstream;
            include /etc/nginx/proxy.conf;
        }}""")
    return HEADER + """worker_processes auto;
pid /tmp/nginx.pid;
error_log /dev/stderr warn;

events {
    worker_connections 1024;
}

http {
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    access_log /dev/stdout;
    sendfile on;
    server_tokens off;

    client_body_temp_path /tmp/client_temp;
    proxy_temp_path /tmp/proxy_temp;
    fastcgi_temp_path /tmp/fastcgi_temp;
    uwsgi_temp_path /tmp/uwsgi_temp;
    scgi_temp_path /tmp/scgi_temp;

    # Docker's embedded DNS. Upstreams are resolved per request (variables in proxy_pass), so
    # the hub starts and keeps serving even while some app containers are down or missing.
    resolver 127.0.0.11 valid=10s ipv6=off;
    resolver_timeout 2s;

    server {
        listen 8080;
        listen [::]:8080;
        add_header X-Content-Type-Options nosniff always;

        location = /healthz {
            access_log off;
            default_type text/plain;
            return 200 "ok\\n";
        }

        # An app that is not deployed (or still starting) answers with a short message instead
        # of nginx's default page; the launcher shows it as not available.
        error_page 502 503 504 = @down;
        location @down {
            default_type text/plain;
            return 503 "This Craft App is not running.\\n";
        }
""" + "".join(locations) + f"""

        # The launcher (hub mode: its index.html says the apps are at ./<id>/) is the front page.
        location / {{
            set $upstream http://{hub}:8080;
            proxy_pass $upstream;
            include /etc/nginx/proxy.conf;
        }}
    }}
}}
"""


def main():
    catalog = json.loads((ROOT / "apps.json").read_text())
    apps = load_apps()
    hub = catalog["hub"]
    assert any(a["id"] == hub for a in apps), f"hub {hub!r} is not in apps"
    files = {
        ROOT / "docker-compose.yml": compose(apps),
        ROOT / "hub" / "nginx.conf": hub_nginx(apps, hub),
    }
    if "--check" in sys.argv:
        stale = [p for p, c in files.items() if not p.exists() or p.read_text() != c]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run scripts/generate.py)", file=sys.stderr)
        sys.exit(1 if stale else 0)
    for p, c in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(c)
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
